"""Build the single transactional post-015 fictional admin SQL Editor setup."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'db' / 'postgres'
sources = ['016_admin_reads.sql', 'grant_test_admin_reads.sql']
sections = []
for name in sources:
    body = (ROOT / name).read_text(encoding='utf-8')
    assert body.count('BEGIN;') == 1 and body.count('COMMIT;') == 1
    sections.append('-- Source: ' + name + '\n' + body.replace('BEGIN;\n', '', 1).rsplit('COMMIT;', 1)[0].rstrip())
output = '-- GENERATED by tools/build_v1_admin_setup.py. Apply once after 015.\n'
output += '-- Disposable test project only; installs read functions and grants ONLY the existing fictional admin.\n'
output += '-- Old sessions are revoked by the existing permission trigger. Sign in again after success.\nBEGIN;\n\n'
output += '\n\n'.join(sections) + '\n\nCOMMIT;\n'
(ROOT / '016_admin_reads_setup.sql').write_text(output, encoding='utf-8')
print('Built db/postgres/016_admin_reads_setup.sql; no database contacted.')
